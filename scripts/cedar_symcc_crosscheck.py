def _file_text(entry: dict[str, str], cache: Path) -> str:
    """The file at its recorded digest, cached as the Cedar exact study caches it."""

    subject = f"{entry['repo']}/{entry['path']}"
    stored = cache / hashlib.sha256(subject.encode()).hexdigest()
    if not (stored.exists() and hashlib.sha256(stored.read_bytes()).hexdigest() == entry["sha256"]):
        content, status = _load("measure_third_party_policies").fetch_bytes(entry)
        if content is None or hashlib.sha256(content).hexdigest() != entry["sha256"]:
            raise SystemExit(f"{subject}: not available at its recorded digest ({status})")
        stored.parent.mkdir(parents=True, exist_ok=True)
        stored.write_bytes(content)
    return stored.read_bytes().decode("utf-8")


def _schema_text(listed: dict[str, Any], cache: Path) -> str:
    schema = listed["schema"]
    candidates = _load("cedar_schema_candidates")
    content = candidates.blob(
        listed["repo"], listed["commit"], schema["path"], schema["blob_sha1"], cache
    )
    if content is None or hashlib.sha256(content).hexdigest() != schema["sha256"]:
        raise SystemExit(f"{listed['subject']}: its schema is not available at its digest")
    return candidates.schema_source(content, schema["path"])[1]


def _tool(command: list[str], binary: str) -> dict[str, str]:
    done = subprocess.run(command, capture_output=True, text=True, check=False)
    resolved = Path(binary)
    return {
        "version": (done.stdout or done.stderr).strip().splitlines()[0],
        "sha256": hashlib.sha256(resolved.read_bytes()).hexdigest() if resolved.is_file() else "",
    }


def _share(numerator: int, denominator: int) -> float | None:
    return round(numerator / denominator, 6) if denominator else None


def summarise(records: list[dict[str, Any]]) -> dict[str, Any]:
    pooled = [r for r in records if not r["development"]]
    mutants = [m for r in pooled if r["status"] == "checked" for m in r["mutants"]]
    equivalent = [m for m in mutants if m["study"] == "equivalent"]
    live = [m for m in mutants if m["study"] == "live"]
    replays = Counter(c["replay"] for m in mutants for c in m["counterexamples"])
    refutations = [
        {
            "file": r["subject"],
            "mutant": m["mutant"],
            **{k: v for k, v in c.items() if k != "replay"},
        }
        for r in pooled
        if r["status"] == "checked"
        for m in r["mutants"]
        if m["class"] == "refuted"
        for c in m["counterexamples"]
        if c["replay"] == "confirmed"
    ]
    schema_equivalent = [m for m in live if m["class"] == "equivalent under the schema"]
    return {
        "files": dict(sorted(Counter(r["status"] for r in pooled).items())),
        "primary": {
            "equivalent_verdicts": len(equivalent),
            "classes": {
                c: sum(1 for m in equivalent if m["class"] == c) for c in EQUIVALENT_CLASSES
            },
            "refutations": refutations,
            "refutations_whose_principal_is_the_resource": sum(
                1 for r in refutations if r.get("principal_is_resource")
            ),
            "with_a_counterexample_the_engine_did_not_confirm": [
                {
                    "file": r["subject"],
                    "mutant": m["mutant"],
                    "replays": [c["replay"] for c in m["counterexamples"]],
                }
                for r in pooled
                if r["status"] == "checked"
                for m in r["mutants"]
                if m["study"] == "equivalent"
                and any(c["replay"] != "confirmed" for c in m["counterexamples"])
            ],
        },
        "secondary": {
            "live_verdicts": len(live),
            "classes": {c: sum(1 for m in live if m["class"] == c) for c in LIVE_CLASSES},
            "share_equivalent_under_the_schema": _share(len(schema_equivalent), len(live)),
            "equivalent_under_the_schema_by_operator": dict(
                sorted(Counter(m["operator"] for m in schema_equivalent).items())
            ),
            "live_by_operator": dict(sorted(Counter(m["operator"] for m in live).items())),
            "counterexamples": dict(sorted(replays.items())),
            "control": {r["subject"]: r.get("control") for r in pooled},
        },
    }


def study(
    cedar: str,
    cvc5: str,
    cache: Path,
    workers: int,
    partial: Path,
    only: list[str] | None = None,
) -> dict[str, Any]:
    require_registration()
    artifact = json.loads((DOCS / "cedar-suite-strategy-study-v1.json").read_text("utf-8"))
    engine = f"cedarpy {importlib.metadata.version('cedarpy')}"
    if engine != artifact["engine"]:
        raise SystemExit(f"the study's engine is {artifact['engine']}, this is {engine}")
    _, internal = _load("cedar_exact_study")._cedar()
    manifest = json.loads((DOCS / "third-party-sample-cedar-corpus-v1.json").read_text("utf-8"))
    index = {f"{entry['repo']}/{entry['path']}": entry for entry in manifest["files"]}
    listed = json.loads(CANDIDATES.read_text("utf-8"))
    done: dict[str, dict[str, Any]] = {}
    if partial.exists():
        for line in partial.read_text("utf-8").splitlines():
            if line.strip():
                record = json.loads(line)
                done[record["subject"]] = record
    tasks: list[dict[str, Any]] = []
    for entry in listed["files"]:
        if not entry["schema"] or entry["subject"] in done:
            continue
        if only and entry["subject"] not in only:
            continue
        text = _file_text(index[entry["subject"]], cache)
        expected = {k: v for k, v in artifact["files"][entry["subject"]]["mutants"].items() if v}
        tasks.append(
            {
                "subject": entry["subject"],
                "text": text,
                "est": internal.policies_to_json_str(text),
                "schema": _schema_text(entry, cache),
                "schema_format": entry["schema"]["format"],
                "schema_path": entry["schema"]["path"],
                "schema_kind": entry["schema"]["kind"],
                "environments": entry["environments"],
                "expected": expected,
                "cedar": cedar,
                "cvc5": cvc5,
            }
        )
    # Heaviest first, so the longest files do not start last.
    tasks.sort(key=lambda t: -len(t["environments"]) * sum(t["expected"].values()))
    context = multiprocessing.get_context("spawn")
    with (
        concurrent.futures.ProcessPoolExecutor(workers, mp_context=context) as pool,
        partial.open("a", encoding="utf-8") as sink,
    ):
        futures = [pool.submit(check_file, task) for task in tasks]
        for future in concurrent.futures.as_completed(futures):
            record = future.result()
            done[record["subject"]] = record
            sink.write(json.dumps(record) + "\n")
            sink.flush()
            print(f"{len(done)} {record['subject']}: {record['status']}", file=sys.stderr)

    records = [done[s] for s in sorted(done)]
    development = [r for r in records if r["development"]]
    return {
        "schema_version": "v1",
        "protocol_sha256": PROTOCOL_SHA256,
        "candidates_sha256": CANDIDATES_SHA256,
        "engine": engine,
        "seed": _load("cedar_exact_study").SEED,
        "tools": {
            "cedar": _tool([cedar, "--version"], cedar),
            "cvc5": _tool([cvc5, "--version"], cvc5),
            "platform": f"{platform.system()} {platform.machine()}",
        },
        "limits": {"wall_clock_seconds": WALL_CLOCK, "solver_ms_per_query": SOLVER_LIMIT_MS},
        "deviations": DEVIATIONS,
        "summary": summarise(records),
        "development": development,
        "files": [r for r in records if not r["development"]],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    run = sub.add_parser("study")
    run.add_argument("--cedar", required=True)
    run.add_argument("--cvc5", required=True)
    run.add_argument("--cache", type=Path, required=True)
    run.add_argument("--workers", type=int, default=4)
    run.add_argument("--partial", type=Path, required=True)
    run.add_argument("--only", nargs="*")
    run.add_argument("--json", type=Path)
    args = parser.parse_args(argv)
    # Absolute paths: Windows does not resolve a relative executable path in the workers.
    cedar, cvc5 = (
        str(Path(tool).resolve()) if Path(tool).is_file() else tool
        for tool in (args.cedar, args.cvc5)
    )
    result = study(cedar, cvc5, args.cache, args.workers, args.partial, args.only)
    text = json.dumps(result, indent=1, ensure_ascii=False)
    if args.json:
        args.json.write_text(text + "\n", encoding="utf-8")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
