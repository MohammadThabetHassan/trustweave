def _load(name: str) -> Any:
    if name in sys.modules:
        return sys.modules[name]
    specification = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    assert specification and specification.loader
    module = importlib.util.module_from_spec(specification)
    sys.modules[name] = module
    specification.loader.exec_module(module)
    return module


def _lf_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def require_registration() -> None:
    for path, fixed in ((PROTOCOL, PROTOCOL_SHA256), (CANDIDATES, CANDIDATES_SHA256)):
        found = _lf_sha256(path)
        if found != fixed:
            raise SystemExit(
                f"{path.name} hashes to {found}, not the {fixed} fixed before the study ran; "
                "a changed protocol or schema list is a different study, so this one refuses "
                "to run"
            )


