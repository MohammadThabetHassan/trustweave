def outcome(returncode: int, stdout: str, stderr: str) -> str:
    """One environment's result, as the protocol names them."""

    if returncode == 0 and VERIFIED in stdout:
        return "verified"
    if returncode == 0 and DOES_NOT_HOLD in stdout:
        return "counterexample"
    if "Failed to compile policy set 2" in stderr:
        return "mutant does not compile"
    if "Failed to compile policy set 1" in stderr:
        return "file does not compile"
    return "no answer"


def symcc(
    cedar: str,
    cvc5: str,
    environment: list[str],
    schema: Path,
    schema_format: str,
    first: Path,
    first_format: str,
    second: Path,
) -> tuple[str, str]:
    principal, action, resource = environment
    command = [
        cedar,
        "symcc",
        "--cvc5-path",
        cvc5,
        "--principal-type",
        principal,
        "--action",
        action,
        "--resource-type",
        resource,
        "--schema",
        str(schema),
        "--schema-format",
        schema_format,
        "--counterexample",
        "equivalent",
        "--policies1",
        str(first),
        "--policies1-format",
        first_format,
        "--policies2",
        str(second),
        "--policies2-format",
        "json",
    ]
    try:
        done = subprocess.run(
            command,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=WALL_CLOCK,
            check=False,
        )
    except subprocess.TimeoutExpired:
        return "wall-clock limit", ""
    result = outcome(done.returncode, done.stdout, done.stderr)
    detail = done.stdout if result == "counterexample" else done.stderr.strip()[-600:]
    return result, detail if result != "verified" else ""


def replay(
    original: dict[str, Any], mutant: dict[str, Any], text: str
) -> tuple[str, dict[str, Any]]:
    """Whether the engine confirms a counterexample: `confirmed`, `unconfirmed` or `unreplayed`."""

    ces = _load("cedar_exact_study")
    cedarpy, _ = ces._cedar()
    try:
        request, entities = parse_counterexample(text)
    except (Unreadable, ValueError) as error:
        return "unreplayed", {"why": str(error)[:200]}
    try:
        batches = ces.batches_of([(request, entities)])
        decided = [
            ces.evaluate(cedarpy.PolicySet.from_json_str(json.dumps(est)), batches, 1)[0][0]
            for est in (original, mutant)
        ]
    except Exception as error:  # noqa: BLE001 - the engine refusing the request is recorded
        return "unreplayed", {"why": f"the engine refused it: {str(error)[:200]}"}
    detail = {
        "file": decided[0],
        "mutant": decided[1],
        "principal_is_resource": request["principal"] == request["resource"],
    }
    return ("confirmed" if decided[0] != decided[1] else "unconfirmed"), detail


def classify(study_verdict: str, results: list[str], replays: list[str]) -> str:
    """A verdict's class from its environments' results and its counterexamples' replays.

    The protocol defines the four classes of an equivalent verdict and the first two of a live
    one. A live verdict in neither is placed by what kept it out: a counterexample the engine
    did not confirm, or an environment without an answer.
    """

    verified = results.count("verified")
    if study_verdict == "equivalent":
        if "confirmed" in replays:
            return "refuted"
        if results and verified == len(results):
            return "not refuted, every environment verified"
        return "not refuted, partly checked" if verified else "unchecked"
    if "confirmed" in replays:
        return "live under the schema"
    if results and verified == len(results):
        return "equivalent under the schema"
    if replays:
        return "counterexample not confirmed"
    return "equivalent where checked" if verified else "unchecked"


def _operator(name: str) -> str:
    if name.startswith("literal_to_"):
        return "literal_to"
    return name.split("[", 1)[0].split("@", 1)[0].rstrip("0123456789")


def check_file(task: dict[str, Any]) -> dict[str, Any]:
    """Reproduce one file's verdicts, run the control, and check every mutant."""

    ces = _load("cedar_exact_study")
    subject = task["subject"]
    est = json.loads(task["est"])
    record: dict[str, Any] = {
        "subject": subject,
        "development": subject == DEVELOPMENT,
        "schema": {"path": task["schema_path"], "kind": task["schema_kind"]},
        "environments": len(task["environments"]),
    }
    analysis = ces.analyse_file(est, generator=random.Random(f"{ces.SEED}:{subject}"))
    statuses = Counter(m["status"] for m in analysis.get("mutants", []))
    record["reproduced"] = dict(sorted(statuses.items()))
    if analysis.get("status") != "scored" or dict(statuses) != task["expected"]:
        record["status"] = "verdicts not reproduced"
        return record
    found = ces.observables_of(est)
    mutants = list(ces.mutants_of(est, found))
    names = [m["mutant"] for m in analysis["mutants"]]
    if [name for name, _ in mutants] != names:
        record["status"] = "verdicts not reproduced"
        return record

    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        text, original, schema = root / "file.cedar", root / "file.json", root / "schema"
        text.write_bytes(task["text"].encode("utf-8"))
        original.write_text(json.dumps(est), encoding="utf-8")
        schema.write_text(task["schema"], encoding="utf-8")
        tools = (task["cedar"], task["cvc5"])

        control: Counter[str] = Counter()
        usable: list[int] = []
        for index, environment in enumerate(task["environments"]):
            result, _ = symcc(
                *tools, environment, schema, task["schema_format"], text, "cedar", original
            )
            control[result] += 1
            if result == "verified":
                usable.append(index)
        record["control"] = dict(sorted(control.items()))
        record["usable_environments"] = len(usable)
        if control.get("counterexample"):
            record["status"] = "JSON form not faithful"
            return record
        if not usable:
            record["status"] = "SymCC does not compile it"
            return record

        checked: list[dict[str, Any]] = []
        for (name, mutated), verdict in zip(mutants, analysis["mutants"], strict=True):
            if verdict["status"] not in ("equivalent", "live"):
                continue
            path = root / "mutant.json"
            path.write_text(json.dumps(mutated), encoding="utf-8")
            results: list[str] = []
            counterexamples: list[dict[str, Any]] = []
            confirmed = False
            for index in usable:
                result, detail = symcc(
                    *tools,
                    task["environments"][index],
                    schema,
                    task["schema_format"],
                    original,
                    "json",
                    path,
                )
                results.append(result)
                if result == "counterexample":
                    replayed, facts = replay(est, mutated, detail)
                    entry = {"environment": index, "replay": replayed, **facts}
                    if replayed != "confirmed" or verdict["status"] == "equivalent":
                        entry["text"] = detail
                    counterexamples.append(entry)
                    confirmed = confirmed or replayed == "confirmed"
                    if confirmed and verdict["status"] == "live":
                        break
            checked.append(
                {
                    "mutant": name,
                    "operator": _operator(name),
                    "study": verdict["status"],
                    "class": classify(
                        verdict["status"], results, [c["replay"] for c in counterexamples]
                    ),
                    "results": dict(sorted(Counter(results).items())),
                    "counterexamples": counterexamples,
                }
            )
        record["status"] = "checked"
        record["mutants"] = checked
    return record


