"""SymCC's check of the Cedar exact study's equivalence verdicts.

Protocol: `docs/CEDAR_SYMCC_CROSSCHECK_PROTOCOL.md`, whose hash is fixed below, as is the hash of
the schema list it was registered on (`docs/cedar-schema-candidates-v1.json`); the script
refuses to run on the population unless both files are the ones committed before it ran.

The Cedar exact study (`cedar_exact_study.py`) calls a mutant equivalent when no cell of its
file's witness space separates it from the file. Here SymCC, Cedar's symbolic compiler, is
asked the same question under the schema the file's own authors wrote, one request environment
at a time, through the `cedar symcc equivalent` command of `cedar-policy-cli` with the cvc5
solver. Every mutant is the study's own, regenerated by the study's code with its seed, and
every counterexample SymCC prints is parsed and decided again by the study's engine, cedarpy,
through the study's evaluation function. Only a counterexample the engine confirms refutes an
equivalent verdict; a verified equivalence holds only for the requests the schema admits.

`cedarpy` must be installed (`pip install cedarpy==4.12.1`), and the Cedar CLI's experimental
build and cvc5 must be on hand; the protocol names the builds and their digests.

Usage:
    python scripts/cedar_symcc_crosscheck.py study --cedar PATH/TO/cedar --cvc5 PATH/TO/cvc5 \\
        --cache DIR --workers 8 --partial PARTIAL.jsonl --json docs/cedar-symcc-crosscheck-v1.json
"""

