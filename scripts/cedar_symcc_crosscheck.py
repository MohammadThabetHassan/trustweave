class Unreadable(ValueError):
    """Counterexample text this parser cannot read; the counterexample is kept unreplayed."""


_ESCAPES = {"n": "\n", "r": "\r", "t": "\t", "0": "\0", "\\": "\\", '"': '"', "'": "'"}


class _Reader:
    """A cursor over the environment SymCC prints (`cedar_policy_symcc::Env`'s Display).

    Values are printed in Cedar's literal syntax with Rust's `escape_debug` for strings:
    entity references as `Type::"id"`, extension values as calls such as `decimal("1.0")`, or
    `(datetime("1970-01-01")).offset(duration("0ms"))` for a datetime, sets in brackets, and
    records in braces with identifier or string keys. A call is passed on in Cedar's JSON form
    for extension values, so the engine, not this parser, computes what it denotes.
    """

    def __init__(self, text: str) -> None:
        self.text = text
        self.at = 0

    def ahead(self, literal: str) -> bool:
        return self.text.startswith(literal, self.at)

    def expect(self, literal: str) -> None:
        if not self.ahead(literal):
            raise Unreadable(f"expected {literal!r} at {self.text[self.at : self.at + 40]!r}")
        self.at += len(literal)

    def string(self) -> str:
        self.expect('"')
        out: list[str] = []
        while True:
            if self.at >= len(self.text):
                raise Unreadable("unterminated string")
            char = self.text[self.at]
            self.at += 1
            if char == '"':
                return "".join(out)
            if char != "\\":
                out.append(char)
                continue
            code = self.text[self.at : self.at + 1]
            self.at += 1
            if code in _ESCAPES:
                out.append(_ESCAPES[code])
            elif code == "u" and self.ahead("{"):
                end = self.text.index("}", self.at)
                out.append(chr(int(self.text[self.at + 1 : end], 16)))
                self.at = end + 1
            else:
                raise Unreadable(f"unknown escape \\{code}")

    def identifier(self) -> str:
        start = self.at
        while self.at < len(self.text) and (
            self.text[self.at].isalnum() or self.text[self.at] == "_"
        ):
            self.at += 1
        if start == self.at or self.text[start].isdigit():
            raise Unreadable(f"expected a name at {self.text[start : start + 40]!r}")
        return self.text[start : self.at]

    def uid(self) -> tuple[str, str]:
        path = [self.identifier()]
        while True:
            self.expect("::")
            if self.ahead('"'):
                return "::".join(path), self.string()
            path.append(self.identifier())

    def arguments(self) -> list[Any]:
        self.expect("(")
        found: list[Any] = []
        while not self.ahead(")"):
            if found:
                self.expect(", ")
            found.append(self.value())
        self.expect(")")
        return found

    def methods(self, receiver: Any) -> Any:
        """`.name(arguments)` calls on a value, as Cedar's JSON writes a call of `name`."""

        while self.ahead("."):
            self.expect(".")
            name = self.identifier()
            receiver = {"__extn": {"fn": name, "args": [receiver, *self.arguments()]}}
        return receiver

    def value(self) -> Any:
        if self.ahead("<unknown>"):
            raise Unreadable("a value SymCC could not concretise")
        if self.ahead("("):
            self.expect("(")
            inner = self.value()
            self.expect(")")
            return self.methods(inner)
        if self.ahead('"'):
            return self.string()
        if self.ahead("["):
            self.expect("[")
            items: list[Any] = []
            while not self.ahead("]"):
                if items:
                    self.expect(", ")
                items.append(self.value())
            self.expect("]")
            return items
        if self.ahead("{"):
            self.expect("{")
            record: dict[str, Any] = {}
            while not self.ahead("}"):
                if record:
                    self.expect(", ")
                key = self.string() if self.ahead('"') else self.identifier()
                self.expect(": ")
                record[key] = self.value()
            self.expect("}")
            return record
        if self.ahead("-") or self.text[self.at : self.at + 1].isdigit():
            start = self.at
            self.at += 1
            while self.text[self.at : self.at + 1].isdigit():
                self.at += 1
            return int(self.text[start : self.at])
        path = [self.identifier()]
        while self.ahead("::"):
            self.expect("::")
            if self.ahead('"'):
                return {"__entity": {"type": "::".join(path), "id": self.string()}}
            path.append(self.identifier())
        if self.ahead("("):
            found = self.arguments()
            name = "::".join(path)
            call = {"fn": name, "arg": found[0]} if len(found) == 1 else {"fn": name, "args": found}
            return self.methods({"__extn": call})
        if path in (["true"], ["false"]):
            return path == ["true"]
        raise Unreadable(f"unknown value {'::'.join(path)!r}")

    def attributes(self) -> dict[str, Any]:
        """`    key: value,` lines up to the closing `  }`; keys are printed as they are."""

        found: dict[str, Any] = {}
        while not self.ahead("  }"):
            self.expect("    ")
            end = self.text.find(": ", self.at)
            if end < 0:
                raise Unreadable("an attribute without a value")
            key = self.text[self.at : end]
            self.at = end + 2
            found[key] = self.value()
            self.expect(",\n")
        self.expect("  }")
        return found


def _cedar_uid(uid: tuple[str, str]) -> str:
    escaped = "".join(
        "\\\\"
        if c == "\\"
        else '\\"'
        if c == '"'
        else c
        if c.isprintable()
        else f"\\u{{{ord(c):x}}}"
        for c in uid[1]
    )
    return f'{uid[0]}::"{escaped}"'


def parse_counterexample(text: str) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """The request and entity store a `cedar symcc` counterexample describes, as cedarpy reads
    them: the request's entities as `Type::"id"` strings, values in Cedar's JSON form."""

    marker = "Counterexample found:\n"
    text = text.replace("\r\n", "\n")
    if marker not in text:
        raise Unreadable("no counterexample in the output")
    reader = _Reader(text.split(marker, 1)[1])
    roles: dict[str, tuple[str, str]] = {}
    for role, lead in (
        ("principal", "principal: "),
        ("action", ", action: "),
        ("resource", ", resource: "),
    ):
        reader.expect(lead)
        roles[role] = reader.uid()
    context: dict[str, Any] = {}
    if reader.ahead("\ncontext: "):
        reader.expect("\ncontext: ")
        context = reader.value()
        if not isinstance(context, dict):
            raise Unreadable("a context that is not a record")
    entities: list[dict[str, Any]] = []
    if reader.ahead("\nentities: [\n"):
        reader.expect("\nentities: [\n")
        while not reader.ahead("]"):
            reader.expect("  ")
            uid = reader.uid()
            parents: list[tuple[str, str]] = []
            if reader.ahead(" in ["):
                reader.expect(" in [")
                while not reader.ahead("]"):
                    if parents:
                        reader.expect(", ")
                    parents.append(reader.uid())
                reader.expect("]")
            attributes: dict[str, Any] = {}
            tags: dict[str, Any] = {}
            if reader.ahead(" {\n"):
                reader.expect(" {\n")
                attributes = reader.attributes()
            if reader.ahead(" tags {\n"):
                reader.expect(" tags {\n")
                tags = reader.attributes()
            reader.expect(",\n")
            entity: dict[str, Any] = {
                "uid": {"__entity": {"type": uid[0], "id": uid[1]}},
                "attrs": attributes,
                "parents": [{"__entity": {"type": t, "id": i}} for t, i in parents],
            }
            if tags:
                entity["tags"] = tags
            entities.append(entity)
        reader.expect("]")
    request = {role: _cedar_uid(uid) for role, uid in roles.items()}
    request["context"] = context
    return request, entities


